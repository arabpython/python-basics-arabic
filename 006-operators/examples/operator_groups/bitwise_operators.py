# عوامل البت Bitwise Operators
# هذه العوامل متقدمة قليلًا، لكن من المفيد معرفة وجودها.

x = 5  # binary: 101
y = 3  # binary: 011

print("x & y =", x & y)
print("x | y =", x | y)
print("x ^ y =", x ^ y)
print("x << 1 =", x << 1)
print("x >> 1 =", x >> 1)

# ملاحظة:
# 5 << 1 تعني إزاحة لليسار، وغالبًا تشبه الضرب في 2.
# 5 >> 1 تعني إزاحة لليمين، وغالبًا تشبه القسمة الصحيحة على 2.
