unique_tags = {"python", "beginner"}  # set

print(student_name, type(student_name))
print(student_age, type(student_age))
print(student_average, type(student_average))
print(is_passed, type(is_passed))
print(skills, type(skills))
print(profile, type(profile))
print(unique_tags, type(unique_tags))
