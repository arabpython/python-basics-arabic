# الفرق بين index في List و key في Dictionary

student_list = ["Sara", 19, "Amman"]

print("Using list index:")
print("Name:", student_list[0])
print("Age :", student_list[1])
print("City:", student_list[2])

student_dict = {
    "name": "Sara",
    "age": 19,
    "city": "Amman"
}

print("\nUsing dictionary key:")
print("Name:", student_dict["name"])
print("Age :", student_dict["age"])
print("City:", student_dict["city"])
